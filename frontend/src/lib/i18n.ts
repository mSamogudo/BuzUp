export type TranslationKey = keyof typeof translations.pt;

export function t(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const texto = translations[locale][key] || translations.pt[key] || key;
  if (!vars) return texto;
  return texto.replace(/\{(\w+)\}/g, (todo, nome) =>
    nome in vars ? String(vars[nome]) : todo);
}
